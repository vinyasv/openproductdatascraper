def _remove_comments(soup: BeautifulSoup):
    """Helper function to remove HTML comments and log the count."""
    count = 0
    comments = soup.find_all(string=lambda text: isinstance(text, Comment))
    for comment in comments:
        comment.extract()
        count += 1
    if count > 0:
        logger.debug(f"Removed {count} HTML comments.")

def preprocess_html(html_content: str, parser: str = 'html.parser', prettify: bool = True) -> Optional[str]:
    """Parses, cleans, extracts main content, and formats HTML string.

    Args:
        html_content: The raw HTML string to parse.
        parser: The BeautifulSoup parser to use (e.g., 'html.parser', 'lxml').
        prettify: Whether to format the output HTML nicely (default: True).

    Returns:
        A string containing the cleaned and formatted HTML of the main content area,
        or None if parsing failed.
    """
    start_time = time.time()
    logger.debug(f"Starting HTML preprocessing using '{parser}'...")
    soup: Optional[BeautifulSoup] = None
    final_html: Optional[str] = None
    status = "Failure"

    try:
        soup = BeautifulSoup(html_content, parser)
        logger.debug("HTML parsing successful.")

        # --- HTML Cleaning (Subtask 5.2) ---
        tags_to_remove = ['script', 'style', 'meta', 'link', 'header', 'footer', 'nav', 'aside', 'form', 'iframe']
        _remove_tags(soup, tags_to_remove)
        _remove_comments(soup)
        logger.debug("HTML cleaning completed.")
        # ------------------------------------

        # --- Main Content Extraction (Subtask 5.3) ---
        content_tag_to_format = None
        content_selectors = [
            'main', '#main-content', '#content', '#product-details',
            '.product-detail', '.pdp-main-content', 'article'
        ]
        found_selector = None
        for selector in content_selectors:
            content_tag_to_format = soup.select_one(selector)
            if content_tag_to_format:
                found_selector = selector
                break

        if content_tag_to_format:
            logger.debug(f"Found main content using selector: '{found_selector}'")
        else:
            logger.warning("Could not find specific main content container. Falling back to <body>.")
            content_tag_to_format = soup.body # Use body tag
            if not content_tag_to_format:
                logger.warning("Could not find <body> tag. Falling back to whole document.")
                content_tag_to_format = soup # Fallback to whole soup
        # ---------------------------------------------

        # --- Formatting (Subtask 5.4) ---
        if content_tag_to_format:
            if prettify:
                final_html = content_tag_to_format.prettify()
            else:
                final_html = str(content_tag_to_format)
            status = "Success"
        # ----------------------------------

    except ParserRejectedMarkup as e:
        logger.error(f"HTML parsing failed (ParserRejectedMarkup): {e}")
    except Exception as e:
        logger.error(f"HTML parsing/preprocessing failed unexpectedly: {e}", exc_info=True)

    end_time = time.time()
    duration = end_time - start_time
    logger.info(f"HTML preprocessing finished. Status: {status}. Duration: {duration:.3f}s")
    return final_html

