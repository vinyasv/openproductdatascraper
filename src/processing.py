async def extract_product_data(markdown_content: str, url: str) -> Optional[ProductData]:
    """Extracts and validates product data from cleaned MARKDOWN using an LLM.

    Args:
        markdown_content: The cleaned Markdown string generated by the crawler.
        url: The original URL of the product page.

    Returns:
        A validated ProductData object if extraction and parsing are successful,
        otherwise None.
    """
    logger.info(f"Starting LLM extraction for: {url} using Markdown")
    start_time = time.time()
    product_data: Optional[ProductData] = None

    client = get_openai_client()
    if not client:
        logger.error("OpenAI client not available for extraction.")
        return None

    # 1. Construct the messages list directly
    system_message = {
        "role": "system",
        "content": "You are an expert data extractor specializing in parsing Markdown content."
    }
    user_message_content = f"""You are an expert data extraction AI. Your task is to extract information about a Sephora product from the provided MARKDOWN content.

The URL of the page is: {url}

Please analyze the following cleaned MARKDOWN content carefully. Look for headings like \"Ingredients\" and \"How to Use\" as well as product names, prices, and image URLs.
```markdown
{markdown_content}
```

Extract the required information and format it STRICTLY as a JSON object matching the schema below.
- Provide the exact URL given above in the \"url\" field.
- For optional fields (price, currency, stock_info, image_url, description, ingredients_list, how_to_use), use `null` if the information cannot be found in the Markdown content. Do NOT guess or make up information.
- It is CRUCIAL to extract the *entire* ingredient list if present under an \"Ingredients\" heading or similar section. Do not truncate or summarize.
- Similarly, extract the *complete* \"how_to_use\" instructions if available under a relevant heading.
- Ensure the output is ONLY the JSON object, with no introductory text, explanations, or markdown formatting around it.

JSON Schema:

{{
  \"product_name\": \"string (Product's full name)\",
  \"url\": \"string (The exact URL provided: {url})\",
  \"price\": \"float | null (Numerical price, null if not found)\",
  \"currency\": \"string | null (Currency code like USD, EUR, null if not found or price is null)\",
  \"stock_info\": \"string | null (Availability status like 'In Stock', 'Out of Stock', 'Coming Soon', null if not found)\",
  \"image_url\": \"string | null (Full URL of the main product image, null if not found)\",
  \"description\": \"string | null (Product description text, null if not found)\",
  \"ingredients_list\": \"string | null (The COMPLETE list of ingredients, exactly as written. If not found, use null. Do NOT summarize or omit ingredients.)\",
  \"how_to_use\": \"string | null (The FULL instructions on how to use the product. If not found, use null.)\"
}}


Output ONLY the JSON object:"""
    user_message = {"role": "user", "content": user_message_content}
    messages = [system_message, user_message]

    # 2. Call the LLM with the messages list
    model_to_use = "gpt-4o" # Or get from config
    raw_llm_output = await call_openai_extract(messages=messages, model=model_to_use)

    # 3. Parse and Validate (Subtask 6.4)
    if raw_llm_output:
        try:
            # Attempt to parse the raw output as JSON
            # Sometimes the LLM might add markdown fences (```json ... ```)
            if raw_llm_output.strip().startswith("```json"):
                json_str = raw_llm_output.strip()[7:-3].strip() # Remove fences
            elif raw_llm_output.strip().startswith("```"):
                 json_str = raw_llm_output.strip()[3:-3].strip()
            else:
                json_str = raw_llm_output.strip()

            data_dict = json.loads(json_str)
            logger.debug(f"Successfully parsed JSON for {url}")

            # Attempt to validate the dictionary against the Pydantic model
            # This automatically checks types, required fields, and runs custom validators
            product_data = ProductData.model_validate(data_dict)
            logger.info(f"Successfully validated product data for {url}")

        except json.JSONDecodeError as e:
            logger.error(f"Failed to parse LLM output as JSON for {url}: {e}")
            logger.debug(f"Raw LLM output that failed parsing:\n{raw_llm_output}") # Log the problematic output
        except ValidationError as e:
            logger.error(f"Pydantic validation failed for {url}: {e}")
            logger.debug(f"Parsed data dict that failed validation: {data_dict if 'data_dict' in locals() else 'N/A'}") # Log the data
        except Exception as e:
            logger.error(f"Unexpected error during parsing/validation for {url}: {e}", exc_info=True)
    else:
        logger.error(f"LLM extraction failed (no output received) for {url}.")

    end_time = time.time()
    duration = end_time - start_time
    status = "Success" if product_data else "Failure"
    logger.info(f"LLM extraction & validation finished for {url}. Status: {status}. Duration: {duration:.3f}s")

    return product_data

